"""High-level atomic persistence port; implementations own explicit host transactions."""

from typing import Protocol
from uuid import UUID

from .models import CandidateRecord, DecisionReceipt, ReviewSnapshot, StageBatch, StagedBatch, StoredRelation


class ReviewerAuthority(Protocol):
    def require(self, principal: object) -> str: ...


class FactStorage(Protocol):
    async def stage(self, batch: StageBatch) -> StagedBatch: ...
    async def get_candidate(self, candidate_id: UUID) -> CandidateRecord | None: ...
    async def review_snapshot(self, candidate_id: UUID) -> ReviewSnapshot: ...
    async def list_candidates(self, *, status: str, limit: int, after_id: UUID | None) -> tuple[CandidateRecord, ...]: ...
    async def receipt(self, request_id: UUID) -> DecisionReceipt | None: ...
    async def decide(self, *, target_id: UUID, kind: str, action: str, reviewer_id: str,
                     request_id: UUID, expected_version: int, snapshot: ReviewSnapshot | None) -> DecisionReceipt: ...
    async def list_relations(self, *, status: str, limit: int, after_id: UUID | None) -> tuple[StoredRelation, ...]: ...
    async def list_decisions(self, target_id: UUID, *, limit: int) -> tuple[DecisionReceipt, ...]: ...
